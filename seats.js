/** 자리 번호(1부터) → { n, name, info, pair } — 없으면 null */
window.seatOf = function (n) {
  n = parseInt(n, 10);
  var S = window.SEATS;
  if (!(n >= 1 && n <= S.length)) return null;
  var p = n % 2 ? n + 1 : n - 1;
  return { n: n, name: S[n - 1][0], info: S[n - 1][1], pair: S[p - 1] ? { n: p, name: S[p - 1][0], info: S[p - 1][1] } : null };
};
